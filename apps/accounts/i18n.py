_IDX = {"ru": 0, "en": 1}


def translate(text, lang):
    if lang in _IDX and text in C:
        return C[text][_IDX[lang]]
    return text


def tr(request, text):
    return translate(text, getattr(request, "lang", DEFAULT))


class LanguageMiddleware:
    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        from django.utils import translation
        lang = request.COOKIES.get("lang", DEFAULT)
        request.lang = lang if lang in _IDX or lang == "uz" else DEFAULT
        translation.activate(request.lang)  # Django'ning o'z xabarlari (masalan, "majburiy maydon") ham shu tilda
        response = self.get_response(request)
        translation.deactivate()
        return response


class DistrictViewMiddleware:
    """OvaBMU: sessiyadagi tanlangan tumanni request.user ga biriktiradi."""

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        u = getattr(request, "user", None)
        role = getattr(u, "role", "") if u is not None and u.is_authenticated else ""
        if role == "ovabmu":
            u.view_district_id = request.session.get("view_district")
        if role in ("ovabmu", "district"):
            u.view_clinic_id = request.session.get("view_clinic")
        return self.get_response(request)
